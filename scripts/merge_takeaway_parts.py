#!/usr/bin/env python3
"""Merge per-range takeaway parts into one module per book.

A long book is written in chapter ranges by several people at once. Each
range lands in scripts/takeaways/parts/<module>_<range>.py with its own
TAKEAWAYS dict, so nobody is editing the same file; this joins them into
scripts/takeaways/<module>.py, which is what apply_takeaways.py reads.

Usage: merge_takeaway_parts.py genesis psalms ...   (or `all`)
"""
import glob
import importlib.util
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PARTS = os.path.join(HERE, 'takeaways', 'parts')


def load(path):
    spec = importlib.util.spec_from_file_location('part', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.TAKEAWAYS


def sort_key(key):
    c, v = key.split(':')
    return int(c), int(v)


def merge(module):
    paths = sorted(glob.glob(os.path.join(PARTS, '%s_*.py' % module)))
    if not paths:
        raise SystemExit('no parts for %s' % module)
    merged, owner = {}, {}
    for path in paths:
        name = os.path.basename(path)
        for key, line in load(path).items():
            if key in merged:
                raise SystemExit('%s: %s written twice (%s and %s)'
                                 % (module, key, owner[key], name))
            merged[key], owner[key] = line, name

    out = [u'#!/usr/bin/env python3',
           u'"""Written one-line takeaways for %s.' % module.title(),
           u'',
           u'Generated by scripts/merge_takeaway_parts.py from',
           u'scripts/takeaways/parts/%s_*.py — edit those, not this file.' % module,
           u'"""',
           u'',
           u'TAKEAWAYS = {']
    last = None
    for key in sorted(merged, key=sort_key):
        chapter = int(key.split(':')[0])
        if chapter != last:
            out.append(u'    # ---- Chapter %d ----' % chapter)
            last = chapter
        out.append(u'    %r: %s,' % (str(key), _literal(merged[key])))
    out.append(u'}')
    path = os.path.join(HERE, 'takeaways', '%s.py' % module)
    with io.open(path, 'w', encoding='utf-8') as fh:
        fh.write(u'\n'.join(out) + u'\n')
    print('%-14s %5d takeaways from %d part(s)' % (module, len(merged), len(paths)))


def _literal(text):
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def main(argv):
    if not argv:
        print(__doc__)
        return 1
    if argv == ['all']:
        argv = sorted({os.path.basename(p).split('_')[0]
                       for p in glob.glob(os.path.join(PARTS, '*.py'))})
    for module in argv:
        merge(module)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
